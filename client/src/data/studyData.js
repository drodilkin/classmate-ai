/**
 * Get all subjects list with summary statistics
 */
export function getSubjectsList() {
  return Object.values(STUDY_DATA).map(subject => ({
    key: subject.key,
    name: subject.name,
    grade: subject.grade,
    icon: subject.icon,
    color: subject.color,
    sectionsCount: subject.sections.length,
    itemsCount: subject.sections.reduce((acc, sec) => acc + sec.items.length, 0)
  }));
}

/**
 * Search across all rules, formulas, and examples
 */
export function searchStudyData(query) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();

  const results = [];

  Object.values(STUDY_DATA).forEach(subject => {
    subject.sections.forEach(sec => {
      sec.items.forEach(item => {
        const matchName = item.name.toLowerCase().includes(q);
        const matchFormula = (item.formula || '').toLowerCase().includes(q);
        const matchRule = (item.rule || '').toLowerCase().includes(q);
        const matchTip = (item.tip || '').toLowerCase().includes(q);
        const matchSec = sec.title.toLowerCase().includes(q);

        if (matchName || matchFormula || matchRule || matchTip || matchSec) {
          results.push({
            subjectKey: subject.key,
            subjectName: subject.name,
            subjectIcon: subject.icon,
            subjectColor: subject.color,
            sectionTitle: sec.title,
            ...item
          });
        }
      });
    });
  });

  return results;
}
